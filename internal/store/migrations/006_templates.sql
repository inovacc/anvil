CREATE TABLE IF NOT EXISTS vault_templates
(
    id
    INTEGER
    PRIMARY
    KEY
    AUTOINCREMENT,
    name
    TEXT
    UNIQUE
    NOT
    NULL,
    description
    TEXT
    DEFAULT
    '',
    template_data
    TEXT
    NOT
    NULL,
    builtin
    INTEGER
    DEFAULT
    0,
    created_at
    DATETIME
    DEFAULT
    CURRENT_TIMESTAMP,
    updated_at
    DATETIME
    DEFAULT
    CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_vault_templates_name ON vault_templates(name);
